#include "test.h"

bool test_semantic_ownership(void) {
    const SemanticCase cases[] = {
        {"launch() { vary a: int[] = ([]); a = ([]); push(a, 1); show(pop(a), length(a)); }", RV_CHECK_OK, NULL},
        {"launch() { vary a = [1]; a = [a[0], pop(a)]; }", RV_CHECK_OK, NULL},
        {"launch() { keep a = [1]; show(length(a), a[0]); walk x in a { show(x); } }", RV_CHECK_OK, NULL},
        {"launch() { vary a = [1]; walk x in a { a[0] = x + 1; } }", RV_CHECK_OK, NULL},
        {"launch() { vary a = [1]; walk x in a { { vary a = [2]; push(a, 3); } } }", RV_CHECK_OK, NULL},
        {"launch() { vary a = [1]; vary b = [2]; walk x in a { push(b, x); } push(a, 3); }", RV_CHECK_OK, NULL},
        {"launch() { walk x in [1, 2] { show(x); } }", RV_CHECK_OK, NULL},
        {"launch() { keep a = [1]; keep b = a; }", RV_CHECK_OWNERSHIP, "fresh literal"},
        {"launch() { vary a = [1]; vary b = [2]; a = b; }", RV_CHECK_OWNERSHIP, "fresh literal"},
        {"launch() { keep a = []; }", RV_CHECK_TYPE, "expected array type"},
        {"launch() { keep a = [[1]]; }", RV_CHECK_TYPE, "primitive"},
        {"object A {} launch() { keep a = [A {}]; }", RV_CHECK_TYPE, "primitive"},
        {"launch() { keep a = [1, 2.0]; }", RV_CHECK_TYPE, "element type"},
        {"launch() { keep a = [1]; a[0] = 2; }", RV_CHECK_OWNERSHIP, "read-only"},
        {"launch() { keep a = [1]; push(a, 2); }", RV_CHECK_OWNERSHIP, "read-only"},
        {"launch() { keep a = [1]; show(pop(a)); }", RV_CHECK_OWNERSHIP, "read-only"},
        {"launch() { vary a = [1]; push(a, 2.0); }", RV_CHECK_TYPE, "element type"},
        {"launch() { push([1], 2); }", RV_CHECK_TYPE, "array binding"},
        {"launch() { show([1][true]); }", RV_CHECK_TYPE, "indexing"},
        {"launch() { vary a = [1]; walk x in a { push(a, 2); } }", RV_CHECK_OWNERSHIP, "active array"},
        {"launch() { vary a = [1]; walk x in a { show(pop(a)); } }", RV_CHECK_OWNERSHIP, "active array"},
        {"launch() { vary a = [1]; walk x in a { a = []; } }", RV_CHECK_OWNERSHIP, "active array"},
        {"launch() { vary a = [1]; vary b = [2]; walk x in a { walk y in b { show(pop(a)); } } }", RV_CHECK_OWNERSHIP, "active array"},
        {"launch() { vary a = [1]; walk x in a { a[0] = pop(a); } }", RV_CHECK_OWNERSHIP, "active array"},
        {"launch() { vary a = [1]; walk x in a { walk y in [pop(a)] {} } }", RV_CHECK_OWNERSHIP, "active array"},
        {"launch() { walk x in [1] { x = 2; } }", RV_CHECK_OWNERSHIP, "read-only"},
        {"launch() { walk i from 0 until 1 { i = 2; } }", RV_CHECK_OWNERSHIP, "read-only"},
        {"launch() { vary f: file = (fileOpen(\"a\", \"r\")); f = (fileOpen(\"b\", \"w\")); fileClose(f); }", RV_CHECK_OK, NULL},
        {"launch() { keep f = fileOpen(\"a\", \"r\"); fileClose(f); }", RV_CHECK_OK, NULL},
        {"launch() { keep f = fileOpen(\"a\", \"r\"); keep g = f; }", RV_CHECK_OWNERSHIP, "fresh fileOpen"},
        {"launch() { vary f = fileOpen(\"a\", \"r\"); vary g = fileOpen(\"b\", \"r\"); f = g; }", RV_CHECK_OWNERSHIP, "fresh fileOpen"},
        {"launch() { keep f = fileOpen(\"a\", \"r\"); f = fileOpen(\"b\", \"r\"); }", RV_CHECK_OWNERSHIP, "read-only"},
        {"craft f(x: int) -> void { x = 2; } launch() {}", RV_CHECK_OWNERSHIP, "read-only"},
        {"craft f(a: int[]) -> void {} launch() {}", RV_CHECK_SYNTAX, NULL},
        {"craft f(a: file) -> void {} launch() {}", RV_CHECK_SYNTAX, NULL},
        {"craft f() -> int[] {} launch() {}", RV_CHECK_SYNTAX, NULL},
        {"craft f() -> file {} launch() {}", RV_CHECK_SYNTAX, NULL},
        {"object A { values: int[]; } launch() {}", RV_CHECK_SYNTAX, NULL},
    };
    return test_semantic_cases(cases, sizeof(cases) / sizeof(cases[0]));
}
